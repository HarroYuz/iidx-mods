"""Compile the reviewed JSON profiles. No disassembly or runtime scanning."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
profiles=[json.loads((ROOT/'addresses'/f'{v}.json').read_text()) for v in ('0909','0917')]
fields=list(profiles[0]['layout'])
assert fields==list(profiles[1]['layout'])
out=['// Generated by tools/generate_addresses.py; edit addresses/*.json.',
     '#pragma once','#include <cstdint>','#include <vector>','namespace addresses {',
     'struct Rva {uintptr_t symbol,value;};',
     'inline constexpr Rva current_rvas[]={']
for key,value in sorted(profiles[1]['addresses'].items(),key=lambda x:int(x[0],16)):
    out.append('    {'+key+','+value['rva']+'},')
out+=['};','struct Layout {']
out+=['    '+('bool' if isinstance(profiles[0]['layout'][key],bool) else 'uint32_t')+' '+key+';' for key in fields]
out+=['};','inline constexpr Layout layouts[]={']
for p in profiles:
    out.append('    {'+','.join(str(p['layout'][key]).lower() for key in fields)+'},')
out+=['};','struct Identity {uint32_t timestamp,entry,image_size;};',
      'inline constexpr Identity identities[]={']
for p in profiles:
    out.append('    {'+','.join(p[key] for key in ('timestamp','entry','image_size'))+'},')
out+=['};','inline std::vector<uintptr_t> count_operands(bool current){',
      '    return current?std::vector<uintptr_t>{'+','.join(hex(x) for x in profiles[1]['menu_count_operands'])+'}:',
      '        std::vector<uintptr_t>{'+','.join(hex(x) for x in profiles[0]['menu_count_operands'])+'};','}',
      'inline const std::vector<uintptr_t> current_record_sites={'+','.join(hex(x) for x in profiles[1]['record_sites'])+'};',
      'inline const std::vector<uintptr_t> current_getter_sites={'+','.join(hex(x) for x in profiles[1]['getter_sites'])+'};',
      '} // namespace addresses','']
(ROOT/'src/address_table.generated.hpp').write_text('\n'.join(out))
if (ROOT/'src/native_bindings.inc').exists():
    lines=['// Generated from addresses/0917.json; targets checked against the supported PE.']
    for b in profiles[1]['bindings']:
        lines.append('BIND('+','.join(b[k] for k in ('purpose','site','target','opcode'))+')')
    (ROOT/'src/native_bindings_0917.inc').write_text('\n'.join(lines)+'\n')
print('Generated both address profiles')
