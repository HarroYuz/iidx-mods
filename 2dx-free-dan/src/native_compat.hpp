template<class Reader> bool compatible_firenet_exit(uintptr_t game,uintptr_t module,
                                                   uintptr_t callback,Reader read){
    if(!module)return false;
    IMAGE_DOS_HEADER dos{};IMAGE_NT_HEADERS64 nt{};
    if(!read(module,dos) || dos.e_magic!=IMAGE_DOS_SIGNATURE || dos.e_lfanew<64 || dos.e_lfanew>4096 ||
       !read(module+dos.e_lfanew,nt) || nt.Signature!=IMAGE_NT_SIGNATURE ||
       nt.FileHeader.Machine!=IMAGE_FILE_MACHINE_AMD64)return false;
    const bool old=nt.FileHeader.TimeDateStamp==0x6aacbc3a && nt.OptionalHeader.SizeOfImage==0x191000 &&
        nt.OptionalHeader.AddressOfEntryPoint==0x87c7c;
    const bool recent=nt.FileHeader.TimeDateStamp==0x6abaa846 && nt.OptionalHeader.SizeOfImage==0x1a6000 &&
        nt.OptionalHeader.AddressOfEntryPoint==0x8808c;
    const bool latest=nt.FileHeader.TimeDateStamp==0x6ad36e3d && nt.OptionalHeader.SizeOfImage==0x1ab000 &&
        nt.OptionalHeader.AddressOfEntryPoint==0x8c89c;
    if(!old && !recent && !latest)return false;
    const auto rva=old?firenet_exit_rva:(recent?firenet_new_exit_rva:firenet_latest_exit_rva);
    const auto saved_rva=old?firenet_saved_exit_rva:(recent?firenet_new_saved_exit_rva:firenet_latest_saved_exit_rva);
    const auto* expected=old?firenet_exit_code:(recent?firenet_new_exit_code:firenet_latest_exit_code);
    uint8_t code[sizeof(firenet_exit_code)]{};uintptr_t saved{};
    static_assert(sizeof(firenet_exit_code)==sizeof(firenet_new_exit_code) && sizeof(firenet_exit_code)==sizeof(firenet_latest_exit_code));
    return callback==module+rva && read(callback,code) && std::memcmp(code,expected,sizeof(code))==0 &&
        read(module+saved_rva,saved) && saved==game+addresses::rva(0x854740);
}
